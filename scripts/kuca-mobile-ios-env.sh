#!/usr/bin/env bash
# Regenerate apps/mobile/ios/.xcode.env.local — run it after every `expo prebuild`.
#
# Why this exists as a script instead of a committed file: the whole `apps/mobile/ios`
# tree is generated and gitignored, so the env file cannot be tracked. It was written by
# hand on 2026-08-05 and would vanish on the next clean prebuild, taking the mirror with
# it.
#
# What the mirror buys (measured 2026-08-05 on the owner's network, same artifact, 5MB):
#
#   repo1.maven.org          17 KB/s      <- React Native's default
#   maven.aliyun.com       20.7 MB/s      <- ~1200x faster; 91MB RN artifact: >1h -> seconds
#   repo.huaweicloud.com   11.1 MB/s      <- fallback
#
# Five consecutive iOS archive failures that day were all downstream of that 17 KB/s:
# the build did not fail on the download, it failed later on half-populated Pods, so the
# errors read as ExpoSQLite missing sqlite3 symbols and dangling RNDeps script paths.
# React Native reads ENTERPRISE_REPOSITORY for rndependencies, rncore and hermes-engine
# alike, so one variable covers all three.
#
# usage: scripts/kuca-mobile-ios-env.sh
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$repo_root/apps/mobile/ios/.xcode.env.local"

if [[ ! -d "$repo_root/apps/mobile/ios" ]]; then
  echo "error: apps/mobile/ios does not exist — run \`expo prebuild\` first" >&2
  exit 1
fi

# Resolve node from PATH rather than pinning a Homebrew Cellar path: the previous file
# hardcoded a specific node version directory, which breaks silently on the next upgrade.
node_binary="$(command -v node || true)"
if [[ -z "$node_binary" ]]; then
  echo "error: node not found on PATH" >&2
  exit 1
fi

mirror="${KUCA_MAVEN_MIRROR:-https://maven.aliyun.com/repository/public}"

cat > "$target" <<EOF
export NODE_BINARY=$node_binary
# Generated by scripts/kuca-mobile-ios-env.sh — do not hand-edit; rerun after prebuild.
# repo1.maven.org measured at 17 KB/s from this network on 2026-08-05; this mirror
# measured at 20.7 MB/s for the same artifact. React Native reads this for
# rndependencies, rncore and hermes-engine alike.
export ENTERPRISE_REPOSITORY=$mirror
EOF

echo "wrote $target"
echo "  NODE_BINARY=$node_binary"
echo "  ENTERPRISE_REPOSITORY=$mirror"
